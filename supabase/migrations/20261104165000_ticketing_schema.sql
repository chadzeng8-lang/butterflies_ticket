create policy "Profiles are visible to their owner or admins"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_ticketing_admin()));

create policy "Admins can manage profiles"
  on public.profiles for all to authenticated
  using ((select public.is_ticketing_admin()))
  with check ((select public.is_ticketing_admin()));

create policy "Published shows are visible to everyone"
  on public.shows for select to anon, authenticated
  using (on_sale or (select public.is_ticketing_admin()));

create policy "Admins can create shows"
  on public.shows for insert to authenticated
  with check ((select public.is_ticketing_admin()));

create policy "Admins can update shows"
  on public.shows for update to authenticated
  using ((select public.is_ticketing_admin()))
  with check ((select public.is_ticketing_admin()));

create policy "Admins can delete shows"
  on public.shows for delete to authenticated
  using ((select public.is_ticketing_admin()));

create policy "Buyers can view their own orders"
  on public.orders for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_ticketing_admin()));

create policy "Admins can update orders"
  on public.orders for update to authenticated
  using ((select public.is_ticketing_admin()))
  with check ((select public.is_ticketing_admin()));

create policy "Buyers can view their own tickets"
  on public.tickets for select to authenticated
  using (
    exists (
      select 1
      from public.orders
      where orders.id = tickets.order_id
        and orders.user_id = (select auth.uid())
    )
    or (select public.is_ticketing_admin())
  );

create policy "Admins can manage tickets"
  on public.tickets for all to authenticated
  using ((select public.is_ticketing_admin()))
  with check ((select public.is_ticketing_admin()));

grant select on public.profiles, public.shows, public.orders, public.tickets to authenticated;
grant select on public.shows to anon;
grant update (full_name) on public.profiles to authenticated;
grant update on public.orders to authenticated;
grant insert, update, delete on public.shows to authenticated;
grant insert, update, delete on public.tickets to authenticated;
grant usage, select on all sequences in schema public to authenticated;


create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  role text not null default 'audience' check (role in ('audience', 'admin')),
  created_at timestamptz not null default now()
);

create table public.shows (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  venue text not null,
  starts_at timestamptz not null,
  capacity integer not null check (capacity > 0),
  ticket_price_cents integer not null default 0 check (ticket_price_cents >= 0),
  deposit_cents integer not null default 0 check (deposit_cents >= 0),
  on_sale boolean not null default false,
  wechat_qr_path text,
  alipay_qr_path text,
  fps_qr_path text,
  payment_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity primary key,
  code text not null unique,
  user_id uuid not null references auth.users (id) on delete restrict,
  show_id bigint not null references public.shows (id) on delete restrict,
  buyer_name text not null,
  phone text not null,
  contact_extra text not null default '',
  quantity integer not null check (quantity between 1 and 5),
  ticket_total_cents integer not null check (ticket_total_cents >= 0),
  deposit_total_cents integer not null check (deposit_total_cents >= 0),
  status text not null check (
    status in (
      'pending_payment',
      'pending_confirm',
      'issued',
      'checked_in',
      'deposit_refunded',
      'cancelled',
      'expired'
    )
  ),
  payment_proof_path text,
  admin_note text not null default '',
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index orders_user_active_idx
  on public.orders (user_id, status);
create index orders_show_active_idx
  on public.orders (show_id, status);
create index orders_created_at_idx
  on public.orders (created_at desc);

create table public.tickets (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete restrict,
  code text not null unique,
  checked_in_at timestamptz,
  deposit_refunded_at timestamptz,
  refunded_by text,
  created_at timestamptz not null default now()
);

create index tickets_order_id_idx on public.tickets (order_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), '')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.is_ticketing_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

create or replace function public.create_ticket_order(
  p_show_id bigint,
  p_buyer_name text,
  p_phone text,
  p_contact_extra text,
  p_quantity integer
)
returns table (order_id bigint, order_code text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_show public.shows%rowtype;
  v_active_seats integer;
  v_user_active_tickets integer;
  v_code text;
  v_attempt integer;
  v_order_id bigint;
  v_timeout_minutes integer := 45;
begin
  if v_user_id is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  if p_quantity is null or p_quantity < 1 or p_quantity > 5 then
    raise exception 'BAD_QUANTITY';
  end if;

  if nullif(btrim(p_buyer_name), '') is null
    or nullif(btrim(p_phone), '') is null then
    raise exception 'BUYER_DETAILS_REQUIRED';
  end if;

  perform 1
  from public.profiles
  where id = v_user_id
  for update;

  select *
  into v_show
  from public.shows
  where id = p_show_id
  for update;

  if not found then
    raise exception 'SHOW_NOT_FOUND';
  end if;

  if not v_show.on_sale then
    raise exception 'SHOW_OFF_SALE';
  end if;

  update public.orders
  set status = 'expired', updated_at = now()
  where status = 'pending_payment'
    and expires_at < now();

  select coalesce(sum(quantity), 0)::integer
  into v_active_seats
  from public.orders
  where show_id = p_show_id
    and status in (
      'pending_payment',
      'pending_confirm',
      'issued',
      'checked_in',
      'deposit_refunded'
    );

  if p_quantity > v_show.capacity - v_active_seats then
    raise exception 'SOLD_OUT';
  end if;

  select coalesce(sum(quantity), 0)::integer
  into v_user_active_tickets
  from public.orders
  where user_id = v_user_id
    and status in (
      'pending_payment',
      'pending_confirm',
      'issued',
      'checked_in',
      'deposit_refunded'
    );

  if v_user_active_tickets + p_quantity > 5 then
    raise exception 'PERSON_TICKET_LIMIT';
  end if;

  for v_attempt in 1..10 loop
    v_code := 'MT-' ||
      substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', floor(random() * 32 + 1)::integer, 1) ||
      substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', floor(random() * 32 + 1)::integer, 1) ||
      substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', floor(random() * 32 + 1)::integer, 1) ||
      substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', floor(random() * 32 + 1)::integer, 1);
    exit when not exists (select 1 from public.orders where code = v_code);
  end loop;

  if exists (select 1 from public.orders where code = v_code) then
    raise exception 'ORDER_CODE_GENERATION_FAILED';
  end if;

  v_timeout_minutes := greatest(
    1,
    least(
      1440,
      coalesce(nullif(current_setting('app.payment_timeout_minutes', true), '')::integer, 45)
    )
  );

  insert into public.orders (
    code,
    user_id,
    show_id,
    buyer_name,
    phone,
    contact_extra,
    quantity,
    ticket_total_cents,
    deposit_total_cents,
    status,
    expires_at
  )
  values (
    v_code,
    v_user_id,
    p_show_id,
    btrim(p_buyer_name),
    btrim(p_phone),
    coalesce(btrim(p_contact_extra), ''),
    p_quantity,
    v_show.ticket_price_cents * p_quantity,
    v_show.deposit_cents * p_quantity,
    'pending_payment',
    now() + make_interval(mins => v_timeout_minutes)
  )
  returning id into v_order_id;

  return query select v_order_id, v_code;
end;
$$;

